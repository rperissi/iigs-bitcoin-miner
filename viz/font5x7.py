# precompute boolean bitmaps
_BMP = {c: np.array([[ch == '1' for ch in row] for row in rows], bool)
        for c, rows in _F.items()}


def text_width(s, sp=1, scale=1):
    return (len(s) * (GW * scale + sp) - sp) if s else 0


def draw_text(arr, x, y, s, rgb, sp=1, scale=1, shadow=None):
    """Stamp string s at (x,y) top-left into arr (H,W,3). Optional 1px shadow."""
    H, W = arr.shape[:2]
    cx = x

    def blk(py0, px0, color):
        for yy in range(scale):
            for xx in range(scale):
                py, px = py0 + yy, px0 + xx
                if 0 <= py < H and 0 <= px < W:
                    arr[py, px] = color

    for ch in s:
        bmp = _BMP.get(ch if ch in _BMP else ch.upper())
        if bmp is None:
            bmp = _BMP[' ']
        if shadow is not None:
            for gy in range(GH):
                for gx in range(GW):
                    if bmp[gy, gx]:
                        blk(y + gy * scale + scale, cx + gx * scale + scale, shadow)
        for gy in range(GH):
            for gx in range(GW):
                if bmp[gy, gx]:
                    blk(y + gy * scale, cx + gx * scale, rgb)
        cx += GW * scale + sp
    return cx
